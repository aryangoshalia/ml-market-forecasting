"""Render the recorded runs into docs/RESULTS.md."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from market_forecast.config import project_root
from market_forecast.evaluation.stats import (
    benjamini_hochberg,
    block_bootstrap_ci,
    paired_fold_test,
    permutation_null_pooled,
)
from market_forecast.experiments.runner import aggregate
from market_forecast.experiments.tracker import ExperimentTracker
from market_forecast.logging import configure

FORMULATIONS = [
    ("direction", 1),
    ("direction", 5),
    ("excess_direction", 1),
    ("excess_direction", 5),
]
MODELS = ["random_forest", "lightgbm", "xgboost", "elastic_net", "logistic", "persistence"]
SHOWN = ["accuracy", "accuracy_over_base_rate", "roc_auc", "pr_auc", "brier", "ece"]


def fold_table(tracker: ExperimentTracker, run_id: str) -> pd.DataFrame:
    fold_metrics = tracker.load_fold_metrics(run_id)
    summary = aggregate(fold_metrics)[SHOWN]
    reference = fold_metrics[fold_metrics["model"] == "majority"]

    extra = []
    for model in summary.index:
        scores = fold_metrics[fold_metrics["model"] == model]
        merged = scores.merge(reference, on="fold", suffixes=("", "_ref"))
        test = paired_fold_test(
            merged["roc_auc"].to_numpy(), merged["roc_auc_ref"].to_numpy(), model, "majority"
        )
        low, high = block_bootstrap_ci(scores["roc_auc"].to_numpy(), seed=7)
        extra.append(
            {
                "model": model,
                "auc_95_lo": low,
                "auc_95_hi": high,
                "folds_won": f"{test.wins}/{test.n_folds}",
                "p_raw": test.p_value,
            }
        )
    joined = summary.join(pd.DataFrame(extra).set_index("model"))
    joined["p_adj"] = benjamini_hochberg(joined["p_raw"].to_numpy())
    return joined.round(4)


def markdown(frame: pd.DataFrame) -> str:
    """Render a table, keeping a named index as its first column and dropping an unnamed one."""
    prepared = frame.reset_index() if frame.index.name else frame
    return prepared.to_markdown(index=False)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=None)
    parser.add_argument("--permutation-draws", type=int, default=400)
    args = parser.parse_args()
    configure("WARNING")

    tracker = ExperimentTracker()
    index = tracker.index()
    main_runs = index[index["experiment"] == "main"]
    first = main_runs.iloc[0]

    lines: list[str] = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from the recorded runs in `experiments/runs/`.",
        "Do not edit by hand.",
        "",
        "## What was run",
        "",
        f"- Universe: {len(first['dataset']['tickers'])} development tickers, "
        f"{first['dataset']['n_sessions']} sessions "
        f"({first['dataset']['first_session']} to {first['dataset']['last_session']})",
        f"- Feature set `{first['feature_version']}`, {first['n_features']} features",
        f"- {first['folds']['count']} anchored walk-forward folds, test coverage "
        f"{first['folds']['first_test']} to {first['folds']['last_test']}",
        "- 8 models per fold: 3 baselines, 5 learners",
        "- 16 runs total: 4 target/horizon combinations x 4 configurations "
        "(main, tuned, 2010 start, rolling window)",
        "",
        "Every number below is out of sample. Preprocessing, calibration, decision thresholds",
        "and hyperparameters were fitted strictly inside each fold's training window.",
        "",
        "The three comparison runs at the end predate a fix to the calibrator, which used to",
        "return probabilities of exactly zero or one for a pure isotonic bin. Their Brier and",
        "calibration error columns therefore come from the earlier code. Ranking metrics are",
        "unaffected, because the fix clips monotonically and cannot reorder predictions, so",
        "every AUC-based conclusion below stands as reported.",
        "",
        "## Reading the tables",
        "",
        "- `accuracy_over_base_rate` compares against the best constant predictor chosen with",
        "  hindsight on that fold, so it is negative whenever a model cannot beat always",
        "  guessing the majority class.",
        "- `roc_auc` is the mean over folds. `auc_95_lo/hi` is a block bootstrap over folds,",
        "  which keeps adjacent folds together because their errors are correlated.",
        "- `folds_won` and `p_adj` come from a paired Wilcoxon signed rank test against the",
        "  majority baseline, adjusted within each table by Benjamini-Hochberg.",
        "",
    ]

    for target, horizon in FORMULATIONS:
        row = main_runs[(main_runs["target"] == target) & (main_runs["horizon"] == horizon)].iloc[
            -1
        ]
        table = fold_table(tracker, row["run_id"])
        predictions = tracker.load_predictions(row["run_id"])
        best = table[~table.index.isin(["majority", "always_long", "persistence"])][
            "roc_auc"
        ].idxmax()
        pooled = predictions[predictions["model"] == best]
        flat = pooled.reset_index()
        null = permutation_null_pooled(
            flat["y_true"].to_numpy(),
            flat["prob"].to_numpy(),
            dates=flat["date"].to_numpy(),
            folds=flat["fold"].to_numpy(),
            draws=args.permutation_draws,
            seed=3,
        )
        verdict = (
            "above the null" if null.observed > null.quantile_95 else "inside the null distribution"
        )
        lines += [
            f"## `{target}` at {horizon} session{'s' if horizon > 1 else ''}",
            "",
            f"Base rate {row['dataset']['base_rate']:.4f}. A model predicting the majority class "
            f"every day scores that accuracy without using any feature.",
            "",
            markdown(table),
            "",
            f"Permutation null for the best learner (`{best}`), pooled over "
            f"{len(pooled):,} predictions. Whole sessions are permuted within each fold, "
            "so fold base rates and same-day cross-sectional structure both survive into "
            "the null and only the link between a prediction and its own outcome is broken:",
            "",
            f"- observed AUC {null.observed:.4f}",
            f"- null {null.mean:.4f} +/- {null.std:.4f}, 95th percentile {null.quantile_95:.4f}",
            f"- p = {null.p_value:.4f} ({verdict})",
            "",
        ]

    held = index[index["experiment"] == "heldout"]
    if not held.empty:
        lines += [
            "## Unseen assets",
            "",
            "Trained on the development group and scored on tickers held out from the start.",
            "Both sides cover the same test windows, so the comparison isolates the effect of",
            "scoring assets the model never saw.",
            "",
        ]
        rows = []
        for target, horizon in FORMULATIONS:
            base = main_runs[(main_runs["target"] == target) & (main_runs["horizon"] == horizon)]
            other = held[(held["target"] == target) & (held["horizon"] == horizon)]
            if base.empty or other.empty:
                continue
            seen = aggregate(tracker.load_fold_metrics(base.iloc[-1]["run_id"]))
            unseen = aggregate(tracker.load_fold_metrics(other.iloc[-1]["run_id"]))
            learners = [m for m in MODELS if m != "persistence" and m in unseen.index]
            best = max(learners, key=lambda m: unseen.loc[m, "roc_auc"])
            rows.append(
                {
                    "formulation": f"{target} h={horizon}",
                    "best on unseen": best,
                    "seen AUC": round(float(seen.loc[best, "roc_auc"]), 4),
                    "unseen AUC": round(float(unseen.loc[best, "roc_auc"]), 4),
                    "change": round(
                        float(unseen.loc[best, "roc_auc"] - seen.loc[best, "roc_auc"]), 4
                    ),
                    "unseen base rate": round(float(other.iloc[-1]["dataset"]["base_rate"]), 4),
                    "unseen tickers": len(other.iloc[-1]["dataset"]["tickers"]),
                }
            )
        lines += [markdown(pd.DataFrame(rows)), ""]

    lines += ["## Configuration comparisons", ""]
    for label, experiment, note in [
        (
            "Tuned versus default hyperparameters",
            "tuned",
            "About 80 configurations searched across 5 models, on validation windows lying "
            "entirely before the first test fold.",
        ),
        (
            "2010 start versus 2005 start",
            "from2010",
            "Fewer folds, so intervals are wider. Compared on shared test sessions elsewhere.",
        ),
        (
            "Rolling versus anchored windows",
            "rolling",
            "A fixed 1260-session training window instead of an expanding one.",
        ),
    ]:
        runs = index[index["experiment"] == experiment]
        if runs.empty:
            continue
        rows = []
        for target, horizon in FORMULATIONS:
            base = main_runs[(main_runs["target"] == target) & (main_runs["horizon"] == horizon)]
            other = runs[(runs["target"] == target) & (runs["horizon"] == horizon)]
            if base.empty or other.empty:
                continue
            a = aggregate(tracker.load_fold_metrics(base.iloc[-1]["run_id"]))["roc_auc"]
            b = aggregate(tracker.load_fold_metrics(other.iloc[-1]["run_id"]))["roc_auc"]
            learners = [m for m in MODELS if m != "persistence"]
            delta = (b[learners] - a[learners]).astype(float)
            rows.append(
                {
                    "formulation": f"{target} h={horizon}",
                    "baseline mean AUC": round(float(a[learners].mean()), 4),
                    "variant mean AUC": round(float(b[learners].mean()), 4),
                    "mean delta": round(float(delta.mean()), 4),
                    "learners improved": f"{int((delta > 0).sum())}/{len(delta)}",
                }
            )
        lines += [f"### {label}", "", note, "", markdown(pd.DataFrame(rows)), ""]

    out = Path(args.out) if args.out else project_root() / "docs" / "RESULTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
